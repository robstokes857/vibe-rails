using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.Data.Sqlite;
using VibeRails.Data.Sqlite;
using Xunit;

namespace Tests.DB;

public sealed class RetiredPrReviewStorageTests
{
    [Fact]
    public void SchemaSetupPreservesLegacyReviewsAndNeverOpensTheRetiredDatabase()
    {
        var directory = Path.Combine(Path.GetTempPath(), "viberails-retired-reviews-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            var state = Path.Combine(directory, "state.db");
            var reviews = Path.Combine(directory, "pr_reviews.db");
            SeedReviews(state);
            SeedReviews(reviews);
            var legacy = ReadReviewData(state);
            var retiredBytes = File.ReadAllBytes(reviews);

            // An older version may still own the retired file. Current initialization must not
            // open it, adopt its contents, change its schema or publish its pending deliveries.
            using (var held = new FileStream(reviews, FileMode.Open, FileAccess.Read, FileShare.None))
                SqliteStorage.EnsureAllSchemas(new SqliteStoragePaths(state));

            Assert.Equal(retiredBytes, File.ReadAllBytes(reviews));
            Assert.Equal(legacy, ReadReviewData(state));
        }
        finally
        {
            SqliteConnection.ClearAllPools();
            Directory.Delete(directory, recursive: true);
        }
    }

    private static void SeedReviews(string path, [System.Runtime.CompilerServices.CallerFilePath] string source = "")
    {
        var root = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(source)!, "..", ".."));
        var snapshot = File.ReadAllText(Path.Combine(root, "docs", "schema", "pr_reviews.sql"));
        using var db = Open(path);
        using var command = db.CreateCommand();
        // Keep the shipped schema as a fixture; it is no longer generated by current stores.
        var tables = Regex.Matches(snapshot, @"(?m)^CREATE TABLE Pr[^\r\n]+;");
        var indexes = Regex.Matches(snapshot, @"(?m)^CREATE (?:UNIQUE )?INDEX [^\r\n]+;");
        command.CommandText = string.Join('\n', tables.Concat(indexes).Select(match => match.Value)) + """

            INSERT INTO PrReviewPullRequests
                (Repository, Number, Title, Author, OpenedUTC, CreatedUTC, UpdatedUTC)
                VALUES ('octo/widgets', 1, 'Keep this review', 'octocat', '2026-01-01', '2026-01-01', '2026-01-01');
            INSERT INTO PrReviews
                (Id, Repository, PrNumber, Status, Feedback, StartedUTC, UpdatedUTC)
                VALUES (1, 'octo/widgets', 1, 'in_progress', 'Unfinished feedback', '2026-01-01', '2026-01-01');
            INSERT INTO PrReviewerSettings VALUES (1, 1);
            INSERT INTO PrReviewerRepositories VALUES ('octo/widgets', 0);
            INSERT INTO PrReviewDeliveries
                (ReviewId, Repository, PrNumber, HeadSha, Event, Body, Marker, Status)
                VALUES (1, 'octo/widgets', 1, 'abc', 'COMMENT', 'Saved feedback', 'receipt', 'pending');
            """;
        command.ExecuteNonQuery();
    }

    private static string ReadReviewData(string path)
    {
        using var db = Open(path);
        using var command = db.CreateCommand();
        command.CommandText = "SELECT name, sql FROM sqlite_schema WHERE type = 'table' AND name LIKE 'PrReview%' ORDER BY name;";
        using var reader = command.ExecuteReader();
        var tables = new List<(string Name, string Sql)>();
        while (reader.Read()) tables.Add((reader.GetString(0), reader.GetString(1)));
        reader.Close();
        var rows = new List<object> { tables.Select(table => table.Sql).ToArray() };
        foreach (var table in tables)
        {
            command.CommandText = $"SELECT * FROM \"{table.Name}\" ORDER BY rowid;";
            using var data = command.ExecuteReader();
            while (data.Read())
            {
                var values = new object[data.FieldCount];
                data.GetValues(values);
                rows.Add(values);
            }
        }
        return JsonSerializer.Serialize(rows);
    }

    private static SqliteConnection Open(string path)
    {
        var connection = new SqliteConnection(new SqliteConnectionStringBuilder { DataSource = path, Pooling = false }.ToString());
        connection.Open();
        return connection;
    }
}
